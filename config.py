"""All configurable project constants in one place. Secrets are loaded from .env and are never stored in the code."""

import os
from pathlib import Path

from dotenv import load_dotenv

# Загружаем переменные из .env в окружение процесса.
# Файл .env должен лежать в корне проекта, рядом с этим файлом.
load_dotenv()


# --- Секреты (берутся из .env, никогда не хранятся в коде) -----------------

BOT_TOKEN = os.getenv("BOT_TOKEN")
FINNHUB_API_KEY = os.getenv("FINNHUB_API_KEY")

if not BOT_TOKEN:
    raise RuntimeError(
        "BOT_TOKEN не найден. Проверь, что файл .env существует в корне "
        "проекта и содержит строку BOT_TOKEN=..."
    )

if not FINNHUB_API_KEY:
    raise RuntimeError(
        "FINNHUB_API_KEY not found. Make sure the .env file exists in the project root and contains FINNHUB_API_KEY"
    )

# --- Путь к файлу базы данных -----------------------------------------------

BASE_DIR = Path(__file__).resolve().parent
